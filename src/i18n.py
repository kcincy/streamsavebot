def tr(language, message, **values):
    return (PT[message] if language=='pt' else message).format(**values)


def decimal(language, value, places=2):
    text=f'{value:.{places}f}'
    return text.replace('.',',') if language=='pt' else text


def date_format(language):
    return '%d/%m/%Y %H:%M' if language=='pt' else '%Y-%m-%d %H:%M'


class UserError(ValueError):
    def __init__(self,message,**values):
        self.message,self.values=message,values
        super().__init__(tr('en',message,**values))

    def translated(self,language):
        return tr(language,self.message,**self.values)
